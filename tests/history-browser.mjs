import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { utils, write } from 'xlsx'
import { mkdir } from 'node:fs/promises'
const browser = await chromium.launch({ channel: process.env.OCR_BROWSER || 'msedge', headless: true })
try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 960 }, locale: 'zh-CN' })
    const page = await context.newPage()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.OCR_URL || 'http://127.0.0.1:5173')
    await page.getByRole('heading', { name: '录入新成绩' }).waitFor()
    await page.waitForFunction(() => !document.body.textContent.includes('正在加载本地成绩'))
    const excel = page.getByRole('dialog', { name: '导入 Excel 成绩', exact: true })
    const details = page.getByRole('dialog', { name: '歌曲信息', exact: true })
    const state = () => page.evaluate(async () => {
        const { scoreRepository } = await import('/src/db/scoreRepository.ts')
        return { history: await scoreRepository.history(), best: await scoreRepository.list(), snapshots: await scoreRepository.snapshots() }
    })
    async function upload(rows, confirm = true) {
        const book = utils.book_new()
        utils.book_append_sheet(book, utils.aoa_to_sheet([['Chart ID', 'Score', 'FC', 'AP', 'Max Chain', '更新时间'], ...rows]), 'BASIC')
        await page.getByLabel('选择成绩截图或 Excel', { exact: true }).setInputFiles({ name: 'history.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(write(book, { type: 'array', bookType: 'xlsx' })) })
        await excel.waitFor()
        await excel.locator('.excel-summary, [role=alert]').first().waitFor()
        assert.equal(await excel.locator('[role=alert]').count(), 0, await excel.textContent())
        const text = await excel.textContent()
        await excel.getByRole('button', { name: confirm ? '确认导入' : '取消', exact: true }).click()
        if (confirm === 'failure') {
            await excel.getByRole('alert').waitFor()
            assert.match(await excel.textContent(), /整批未写入/)
            await excel.getByRole('button', { name: '取消', exact: true }).click()
        }
        await excel.waitFor({ state: 'hidden' })
        return text
    }
    async function go(name) { await page.evaluate(name => { location.hash = `#${name}` }, name); await page.locator(name === 'home' ? '.rating-trend' : '.score-table').first().waitFor() }
    await upload([['1-basic-easy', 1000000]])
    assert.equal((await state()).history.length, 1)
    const duplicate = await upload([['1-basic-easy', 1000000, false, false, null, '2020-01-01T00:00:00Z']])
    assert.match(duplicate, /重复跳过 1 条/)
    assert.equal((await state()).history.length, 1)
    await upload([['1-basic-easy', 900000]])
    await upload([['1-basic-easy', 1000000]])
    assert.equal((await state()).history.length, 3)
    await upload([['1-basic-easy', 1000000, false, false, 0]])
    assert.equal((await state()).history.length, 4)
    assert.equal((await state()).best[0].maxChain, 0)
    const selection = await upload([
        ['1-basic-normal', 800000],
        ['1-basic-normal', 1040000, false, false, 10, '2026-01-01T00:00:00Z'],
        ['1-basic-normal', 1040000, true, false, 20, '2026-02-01T00:00:00Z'],
        ['1-basic-normal', 1040000, true, false, 20, '2026-02-01T00:00:00Z'],
    ])
    assert.match(selection, /重复跳过 1 条/)
    assert.match(selection, /候选忽略 2 条/)
    const normal = (await state()).history.find(row => row.chartId === '1-basic-normal')
    assert.equal(normal.maxChain, 20)
    assert.equal(normal.fc, true)
    assert.equal(normal.updatedAt, Date.parse('2026-02-01T00:00:00Z'))
    await upload([['1-basic-hard', 1000000]], false)
    assert.equal((await state()).history.length, 5)
    // 模拟第二条记录的存储失败，验收整批回滚及错误反馈
    const beforeFailure = await state()
    await page.evaluate(async () => {
        const { database } = await import('/src/db/database.ts')
        window.failHistoryWrite = (_key, row) => { if (row.chartId === '1-basic-master') throw new Error('模拟存储失败') }
        database.scoreHistory.hook('creating', window.failHistoryWrite)
    })
    await upload([['1-basic-hard', 1000000], ['1-basic-master', 1000000]], 'failure')
    assert.deepEqual(await state(), beforeFailure)
    await page.evaluate(async () => (await import('/src/db/database.ts')).database.scoreHistory.hook('creating').unsubscribe(window.failHistoryWrite))
    await page.reload()
    await page.locator('.history-table tbody tr').first().waitFor()
    assert.match(await page.locator('.history-table tbody tr').first().textContent(), /NORMAL/)
    // 实际编辑修正关联历史，不新增记录，降分后恢复其他历史为最佳
    await go('scores')
    assert.equal(await page.getByRole('button', { name: '删除成绩' }).count(), 0)
    const easyRow = page.locator('tbody tr').filter({ hasText: 'EASY' })
    await easyRow.getByRole('button', { name: '编辑成绩' }).click()
    const editor = page.locator('dialog[open]')
    await editor.getByLabel('Score', { exact: true }).fill('850000')
    await editor.getByRole('checkbox').check()
    await editor.getByRole('button', { name: '保存成绩', exact: true }).click()
    await editor.waitFor({ state: 'hidden' })
    assert.equal((await state()).history.length, 5)
    assert.equal((await state()).best.find(row => row.chartId === '1-basic-easy').score, 1000000)
    await easyRow.getByRole('button', { name: '歌曲信息' }).click()
    assert.equal(await details.locator('.chart-detail').count(), 4)
    await details.locator('tbody tr').nth(4).waitFor()
    assert.equal(await details.locator('tbody tr').count(), 5)
    await details.getByRole('button', { name: 'ADVANCED', exact: true }).click()
    await details.getByText('暂无历史成绩', { exact: true }).waitFor()
    await details.getByRole('button', { name: 'BASIC', exact: true }).click()
    await details.locator('tbody tr').first().waitFor()
    // 删除同分补录会撤销其 Max Chain，删除最高分会回退剩余历史
    const chain = details.locator('tbody tr').filter({ hasText: 'EASY' }).filter({ hasText: 'Max Chain 0' }).filter({ hasText: '1,000,000' })
    await chain.getByRole('button', { name: '删除历史成绩' }).click()
    await page.getByRole('button', { name: '确认删除', exact: true }).click()
    await page.getByRole('button', { name: '确认删除', exact: true }).waitFor({ state: 'hidden' })
    assert.equal((await state()).best.find(row => row.chartId === '1-basic-easy').maxChain, undefined)
    assert.ok(await details.isVisible())
    await page.setViewportSize({ width: 390, height: 844 })
    await mkdir('.preview', { recursive: true })
    await page.screenshot({ animations: 'disabled', path: '.preview/history-details-mobile.png', fullPage: true })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await details.getByRole('button', { name: '关闭歌曲信息' }).click()
    // 准备跨日、月、年的持久化历史，再通过页面删除和切换粒度验收可见走势
    await page.evaluate(async () => {
        const { database } = await import('/src/db/database.ts')
        const { scoreRepository } = await import('/src/db/scoreRepository.ts')
        await scoreRepository.clear()
        const now = new Date(), dates = [new Date(now.getFullYear() - 1, 11, 30, 12), new Date(now.getFullYear(), 0, 2, 12), new Date(now.getFullYear(), 1, 2, 12)]
        await database.scoreHistory.bulkAdd(dates.map((date, index) => ({ songId: '1', chartId: '1-basic-hard', score: [900000, 1000000, 1040000][index], fc: false, ap: false, rating: 0, source: 'ocr', importedAt: date.getTime(), updatedAt: date.getTime(), batchId: `fixture-${index}` })))
        await database.metadata.clear()
        await scoreRepository.initialize()
    })
    await go('home')
    const trend = page.locator('.rating-trend')
    assert.equal(await trend.getByRole('button', { name: '日', exact: true }).getAttribute('aria-pressed'), 'true')
    const initialRating = (await state()).snapshots.at(-1).basic
    assert.match(await trend.locator('.trend-value').textContent(), new RegExp(initialRating.toFixed(2)))
    await trend.getByRole('button', { name: '月', exact: true }).click()
    await trend.getByRole('img').click({ position: { x: 1, y: 1 } })
    assert.match(await trend.locator('.trend-value').textContent(), /(?:12月|\/12)/)
    await trend.getByRole('button', { name: '年', exact: true }).click()
    await trend.getByRole('img').click({ position: { x: 1, y: 1 } })
    const previousYear = await page.evaluate(() => new Date().getFullYear() - 1)
    assert.match(await trend.locator('.trend-value').textContent(), new RegExp(String(previousYear)))
    await go('scores'); await go('home')
    assert.equal(await trend.getByRole('button', { name: '年', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.locator('.rating-mode-toggle').click()
    assert.match(await trend.locator('.trend-value').textContent(), /0.00 RT/)
    await page.locator('.rating-mode-toggle').click()
    await page.locator('.history-table tbody tr').first().getByRole('button').first().click()
    await details.locator('tbody tr').first().getByRole('button', { name: '删除历史成绩' }).click()
    await page.getByRole('button', { name: '确认删除', exact: true }).click()
    await page.getByRole('button', { name: '确认删除', exact: true }).waitFor({ state: 'hidden' })
    assert.equal((await state()).best[0].score, 1000000)
    assert.ok((await state()).snapshots.at(-1).basic < initialRating)
    await details.getByRole('button', { name: '关闭歌曲信息' }).click()
    await page.screenshot({ animations: 'disabled', path: '.preview/history-home-mobile.png', fullPage: true })
    await page.setViewportSize({ width: 1280, height: 960 })
    await page.screenshot({ animations: 'disabled', path: '.preview/history-home-desktop.png', fullPage: true })
    await page.reload()
    await page.locator('.history-table tbody tr').first().waitFor()
    assert.equal((await state()).history.length, 2)
    await page.locator('.history-table tbody tr').first().getByRole('button').first().click()
    for (let i = 0; i < 2; i++) {
        await details.locator('tbody tr').first().getByRole('button', { name: '删除历史成绩' }).click()
        await page.getByRole('button', { name: '确认删除', exact: true }).click()
        await page.getByRole('button', { name: '确认删除', exact: true }).waitFor({ state: 'hidden' })
    }
    await details.getByText('暂无历史成绩', { exact: true }).waitFor()
    assert.deepEqual(await state(), { history: [], best: [], snapshots: [] })
    await details.getByRole('button', { name: '关闭歌曲信息' }).click()
    // 两个标签页同时确认同一份文件，只保留一份历史
    const second = await page.context().newPage()
    await second.goto(process.env.OCR_URL || 'http://127.0.0.1:5173')
    await second.getByRole('heading', { name: '录入新成绩' }).waitFor()
    await second.waitForFunction(() => !document.body.textContent.includes('正在加载本地成绩'))
    const concurrentBook = utils.book_new()
    utils.book_append_sheet(concurrentBook, utils.aoa_to_sheet([['Chart ID', 'Score'], ['1-basic-hard', 1000000]]), 'BASIC')
    const concurrentFile = { name: 'concurrent.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(write(concurrentBook, { type: 'array', bookType: 'xlsx' })) }
    for (const target of [page, second]) {
        await target.getByLabel('选择成绩截图或 Excel', { exact: true }).setInputFiles(concurrentFile)
        await target.locator('.excel-summary').waitFor()
    }
    await Promise.all([page, second].map(target => target.getByRole('button', { name: '确认导入', exact: true }).click()))
    await Promise.all([page, second].map(target => target.getByRole('dialog', { name: '导入 Excel 成绩' }).waitFor({ state: 'hidden' })))
    assert.equal((await state()).history.length, 1)
    await second.close()
    // 准备多页历史，验收全局排序、歌曲内分页和清空
    await page.evaluate(async () => {
        const { database } = await import('/src/db/database.ts')
        const { scoreRepository } = await import('/src/db/scoreRepository.ts')
        await scoreRepository.clear()
        const now = Date.now()
        await database.scoreHistory.bulkAdd(Array.from({ length: 35 }, (_, index) => ({ songId: '1', chartId: '1-basic-hard', score: 900000 + index, fc: false, ap: false, rating: 0, source: 'ocr', importedAt: now - (35 - index) * 86400000, updatedAt: now, batchId: `pagination-${index}` })))
        await database.metadata.clear()
        await scoreRepository.initialize()
    })
    await page.getByRole('navigation', { name: '历史成绩分页' }).waitFor()
    assert.equal(await page.locator('.history-table tbody tr').count(), 10)
    await page.locator('.history-table').getByRole('button', { name: '下一页' }).click()
    await page.locator('.history-table tbody tr').first().getByText('900,024', { exact: false }).waitFor()
    assert.match(await page.locator('.history-table tbody tr').first().textContent(), /900,024/)
    await page.locator('.history-table').getByRole('button', { name: /^Score/ }).click()
    await page.locator('.history-table tbody tr').first().getByText('900,034', { exact: false }).waitFor()
    assert.match(await page.locator('.history-table tbody tr').first().textContent(), /900,034/)
    await page.locator('.history-table').getByRole('button', { name: /^Score/ }).click()
    await page.locator('.history-table tbody tr').first().getByText('900,000', { exact: false }).waitFor()
    assert.match(await page.locator('.history-table tbody tr').first().textContent(), /900,000/)
    await page.locator('.history-table tbody tr').first().getByRole('button').first().click()
    await page.waitForFunction(() => document.querySelectorAll('.song-dialog tbody tr').length === 30)
    assert.equal(await details.locator('tbody tr').count(), 30)
    await details.getByRole('button', { name: '下一页' }).click()
    await page.waitForFunction(() => document.querySelectorAll('.song-dialog tbody tr').length === 5)
    assert.equal(await details.locator('tbody tr').count(), 5)
    // 删空末页后回到有效页，关闭重开恢复默认历史排序和第一页
    for (let remaining = 4; remaining >= 0; remaining--) {
        await details.locator('tbody tr').first().getByRole('button', { name: '删除历史成绩' }).click()
        await page.getByRole('button', { name: '确认删除', exact: true }).click()
        await page.getByRole('button', { name: '确认删除', exact: true }).waitFor({ state: 'hidden' })
        await page.waitForFunction(expected => document.querySelectorAll('.song-dialog tbody tr').length === expected, remaining || 30)
    }
    assert.equal(await details.getByRole('navigation', { name: '历史成绩分页' }).count(), 0)
    await details.locator('tbody tr').first().getByText('900,034', { exact: false }).waitFor()
    await details.getByRole('button', { name: /^等级：/ }).click()
    await page.keyboard.press('Escape')
    await details.waitFor({ state: 'hidden' })
    await page.locator('.history-table tbody tr').first().getByRole('button').first().click()
    await details.locator('tbody tr').first().getByText('900,034', { exact: false }).waitFor()
    assert.equal(await details.getByRole('button', { name: /^成绩时间：/ }).getAttribute('aria-label'), '成绩时间：当前降序，点击升序')
    await page.screenshot({ animations: 'disabled', path: '.preview/history-details-desktop.png', fullPage: true })
    await page.keyboard.press('Escape')
    await details.waitFor({ state: 'hidden' })
    // 模拟历史存储读取失败，通过重试按钮恢复可见数据
    await page.evaluate(async () => {
        const { database } = await import('/src/db/database.ts')
        window.historyOrderBy = database.scoreHistory.orderBy
        database.scoreHistory.orderBy = () => { throw new Error('模拟历史读取失败') }
    })
    await page.locator('.history-table').getByRole('button', { name: /^Rank：/ }).click()
    await page.locator('.history-table').getByRole('alert').waitFor()
    assert.match(await page.locator('.history-table').getByRole('alert').textContent(), /无法读取历史成绩/)
    await page.evaluate(async () => { (await import('/src/db/database.ts')).database.scoreHistory.orderBy = window.historyOrderBy })
    await page.locator('.history-table').getByRole('button', { name: '重试', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('.history-table [role=alert]') && document.querySelector('.history-table .table-scroll').getAttribute('aria-busy') === 'false')
    assert.equal(await page.locator('.history-table tbody tr').count(), 10)
    await page.evaluate(() => { location.hash = '#settings' })
    await page.getByRole('button', { name: '清空数据', exact: true }).click()
    await page.getByRole('button', { name: '确认清空全部成绩', exact: true }).click()
    await page.getByRole('button', { name: '确认清空全部成绩', exact: true }).waitFor({ state: 'hidden' })
    await page.reload()
    await page.getByRole('heading', { name: '本地数据' }).waitFor()
    assert.deepEqual(await state(), { history: [], best: [], snapshots: [] })
    assert.deepEqual(errors, [])
    console.log('History acceptance passed: real XLSX selection/deduplication, persistence, edit, per-history deletion, mode details, corrected trends, calendar grains and mobile')
} finally { await browser.close() }
