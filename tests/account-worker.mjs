    await check(await a.api('/api/album/media', 'POST', {}), 401)
    assert.equal((await check(await b.api('/api/nintendo/binding'), 200)).status, 'active')
    const reset = await check(await b.api('/api/account/avatar', 'DELETE'), 200)
    assert.equal(reset.user.avatarUrl, 'https://avatars.example.test/ns.png')
    await check(await b.api('/api/nintendo/binding', 'DELETE'), 200)
    assert.equal((await check(await b.api('/api/nintendo/binding'), 200)).status, 'unbound')
    await check(await b.api('/api/album/media', 'POST', {}), 401)
    // 通过公开登录接口并发消费同一码，只允许一次成功
    const parallel = app.device()
    // 为验证码登录验收准备已有账号，不通过登录接口隐式注册
    for (const email of ['parallel', 'wrong', 'expired', 'rotate', 'limited', 'failure', 'timeout', 'budget-a', 'budget-b'].map(name => `${name}@example.test`)) {
        await app.db.prepare('INSERT INTO user (id, name, email, emailVerified, createdAt, updatedAt) VALUES (?, ?, ?, 1, ?, ?)')
            .bind(crypto.randomUUID(), '', email, Date.now(), Date.now()).run()
    }
    await check(await parallel.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'parallel@example.test' }), 200)
    const otp = app.emails.get('parallel@example.test')
    const outcomes = await Promise.all([parallel.api('/api/auth/sign-in/email-otp', 'POST', { email: 'parallel@example.test', otp }), parallel.api('/api/auth/sign-in/email-otp', 'POST', { email: 'parallel@example.test', otp })])
    assert.equal(outcomes.filter(response => response.ok).length, 1)
    const successful = outcomes.find(response => response.ok)
    for (const cookie of successful.headers.getSetCookie()) {
        assert.match(cookie, /HttpOnly/i)
        assert.match(cookie, /Secure/i)
        assert.match(cookie, /SameSite=Strict/i)
    }
    assert.equal((await successful.json()).token, undefined)
    await app.db.prepare('DELETE FROM rateLimit').run()
    // 准备过期时间与额度边界，通过 HTTP 验收失效、失败次数、重发和免费额度耗尽
    await check(await parallel.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'wrong@example.test' }), 200)
    const correct = app.emails.get('wrong@example.test')
    const wrong = correct === '000000' ? '111111' : '000000'
    for (let attempt = 0; attempt < 5; attempt++) await check(await parallel.api('/api/auth/sign-in/email-otp', 'POST', { email: 'wrong@example.test', otp: wrong }), 400)
    await check(await parallel.api('/api/auth/sign-in/email-otp', 'POST', { email: 'wrong@example.test', otp: correct }), 403)
    await check(await parallel.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'expired@example.test' }), 200)
