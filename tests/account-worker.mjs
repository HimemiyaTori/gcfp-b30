    const old = app.emails.get('rotate@example.test')
    await app.db.prepare('DELETE FROM account_limits').run()
    await check(await parallel.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'rotate@example.test' }), 200)
    const replacement = app.emails.get('rotate@example.test')
    if (replacement !== old) await check(await parallel.api('/api/auth/sign-in/email-otp', 'POST', { email: 'rotate@example.test', otp: old }), 400)
    await check(await parallel.api('/api/auth/sign-in/email-otp', 'POST', { email: 'rotate@example.test', otp: replacement }), 200)
    await app.db.prepare('DELETE FROM rateLimit').run()
