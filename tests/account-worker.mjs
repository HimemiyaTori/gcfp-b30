    assert.equal((await check(await b.api('/api/account'), 200)).user.avatarUrl, 'https://avatars.example.test/nintendo.png')
    await check(await a.api('/api/nintendo/auth/complete', 'POST', { callback }), 400)
    assert.ok(!a.jar.has('__Host-nintendo-session'))
    const rawBinding = await app.db.prepare('SELECT credentials FROM nintendo_bindings WHERE user_id = ?').bind(user.id).first()
    assert.ok(!rawBinding.credentials.includes('nintendo-session-secret'))
    await check(await b.api('/api/album/media', 'POST', {}), 200)
    const afterScan = await check(await b.api('/api/account'), 200)
    assert.equal(afterScan.user.avatarUrl, 'https://avatars.example.test/ns.png')
    await check(await a.api('/api/album/media', 'POST', {}), 429)
    const avatar = await sharp({ create: { width: 256, height: 256, channels: 3, background: '#66aacc' } }).webp().toBuffer()
    const custom = await check(await a.api('/api/account/avatar', 'PUT', avatar), 200)
    assert.match(custom.user.avatarUrl, /^\/api\/account\/avatar\?v=/)
    assert.equal((await check(await b.api('/api/account'), 200)).user.avatarUrl, custom.user.avatarUrl)
    const avatarDownload = await b.api(custom.user.avatarUrl)
    assert.equal(avatarDownload.headers.get('content-type'), 'image/webp')
    assert.deepEqual(Buffer.from(await avatarDownload.arrayBuffer()), avatar)
    await app.db.prepare('UPDATE nintendo_bindings SET next_allowed_at = 0, coral_cache = NULL').run()
    await check(await b.api('/api/album/media', 'POST', {}), 200)
    assert.equal((await check(await a.api('/api/account'), 200)).user.avatarUrl, custom.user.avatarUrl)
    await check(await a.api('/api/account/avatar', 'PUT', Buffer.from('<svg/>')), 400)
    await check(await a.api('/api/account/avatar', 'PUT', Buffer.alloc(102401)), 413)
    await check(await a.api('/api/account/avatar', 'PUT', await sharp({ create: { width: 600, height: 600, channels: 3, background: '#123456' } }).webp().toBuffer()), 400)
    await other.signIn('other@example.test')
    await check(await other.api(custom.user.avatarUrl), 404)
    await check(await other.api('/api/account', 'PATCH', { nickname: 'hijack' }, { 'X-App-Account-Id': user.id }), 409)
