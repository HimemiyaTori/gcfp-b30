    assert.equal((await check(await passwordless.api('/api/auth/set-password', 'POST', { newPassword: 'first-account-password' }), 200)).user.hasPassword, true)
    assert.equal((await check(await passwordless.api('/api/auth/set-password', 'POST', { newPassword: 'cannot-replace-password' }), 400)).error, 'password_already_set')
    await check(await passwordlessOther.api('/api/auth/sign-in/email', 'POST', { email: passwordlessUser.email, password: 'first-account-password' }), 200)
    console.log('Account HTTP acceptance passed: password change validates the current password, revokes other sessions and preserves this device; OTP-only accounts can set a first password after recent login; registration, profile, NS binding and isolation remain valid')
