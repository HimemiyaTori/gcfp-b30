    assert.equal((await check(await a.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'limited@example.test' }), 429)).error, 'email_provider_limited')
    app.control.mailMode = 'failure'
    assert.equal((await check(await a.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'failure@example.test' }), 503)).error, 'email_send_failed')
    app.control.mailMode = 'timeout'
    assert.equal((await check(await a.api('/api/auth/email-otp/send-verification-otp', 'POST', { email: 'timeout@example.test' }), 503)).error, 'email_send_uncertain')
    app.control.mailMode = ''
    await app.db.prepare('DELETE FROM account_limits').run()
    await app.db.prepare('DELETE FROM rateLimit').run()
    const day = `resend:day:${new Date().toISOString().slice(0, 10)}`
