async function profileFits(dialog) {
    const layout = await dialog.evaluate(element => ({
        width: element.clientWidth,
        content: element.scrollWidth,
        viewport: innerWidth,
        bounds: element.getBoundingClientRect().toJSON(),
        overflowing: [...element.querySelectorAll('*')].filter(child => child.getBoundingClientRect().right > element.getBoundingClientRect().right).map(child => ({ tag: child.tagName, class: child.className, type: child.getAttribute('type'), width: child.getBoundingClientRect().width })),
    }))
    assert.ok(layout.content <= layout.width, `Profile dialog content exceeds its width: ${JSON.stringify(layout)}`)
    assert.ok(layout.bounds.left >= 0 && layout.bounds.right <= layout.viewport, `Profile dialog exceeds the viewport: ${JSON.stringify(layout)}`)
}
