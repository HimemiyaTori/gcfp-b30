async function passwordVisibility(dialog, label, value) {
    const field = dialog.getByLabel(label, { exact: true })
    const control = field.locator('..')
    await field.fill(value)
    assert.equal(await field.getAttribute('type'), 'password')
    await control.getByRole('button', { name: '显示密码', exact: true }).click()
    assert.equal(await field.getAttribute('type'), 'text')
    assert.equal(await field.inputValue(), value)
    await control.getByRole('button', { name: '隐藏密码', exact: true }).press('Space')
    assert.equal(await field.getAttribute('type'), 'password')
    await control.getByRole('button', { name: '显示密码', exact: true }).press('Enter')
    assert.equal(await field.getAttribute('type'), 'text')
    await control.getByRole('button', { name: '隐藏密码', exact: true }).click()
    assert.equal(await field.getAttribute('type'), 'password')
    assert.equal(await field.inputValue(), value)
}
